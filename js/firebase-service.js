/**
 * Get active Questions.
 *
 * RTDB does not automatically sort numeric
 * "order" values the same way Firestore does,
 * so we sort them after reading.
 */
export async function getActiveQuestions() {
  const snapshot =
    await get(
      ref(db, PATHS.questions)
    );

  if (!snapshot.exists()) {
    return [];
  }

  const data =
    snapshot.val();

  return Object.entries(data)
    .map(([id, question]) => ({
      id,
      ...question
    }))
    .filter(
      (question) =>
        question.active === true
    )
    .sort(
      (a, b) =>
        Number(a.order || 0) -
        Number(b.order || 0)
    );
}


