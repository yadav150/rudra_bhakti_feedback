/**
 * Convert Firebase timestamp / Date /
 * ISO string into JavaScript Date.
 */
export function toJSDate(
  value
) {
  if (!value) {
    return null;
  }

  if (
    value instanceof Date
  ) {
    return value;
  }

  if (
    typeof value === "number"
  ) {
    const date =
      new Date(value);

    return Number.isNaN(
      date.getTime()
    )
      ? null
      : date;
  }

  const date =
    new Date(value);

  return Number.isNaN(
    date.getTime()
  )
    ? null
    : date;
}


/**
 * Format milliseconds.
 */
export function formatDuration(
  milliseconds
) {
  const ms =
    Number(milliseconds) || 0;

  if (ms <= 0) {
    return "—";
  }

  const totalSeconds =
    Math.round(ms / 1000);

  const minutes =
    Math.floor(
      totalSeconds / 60
    );

  const seconds =
    totalSeconds % 60;

  if (minutes > 0) {
    return `${minutes}m ${seconds}s`;
  }

  return `${seconds}s`;
}


