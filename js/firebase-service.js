import {
  db
} from "./firebase.js";

import {
  ref,
  get,
  set,
  push,
  update,
  query,
  orderByChild,
  equalTo,
  limitToLast,
  serverTimestamp
} from
  "https://www.gstatic.com/firebasejs/12.2.1/firebase-database.js";


/* =========================================================
   DATABASE PATHS
   ========================================================= */

const PATHS = {
  reels: "reels",
  questions: "questions",
  feedback: "feedback",
  admins: "admins"
};


/* =========================================================
   REEL SERVICES
   ========================================================= */

/**
 * Get one Reel.
 *
 * Example:
 * getReel("RB0001")
 */
export async function getReel(reelId) {
  if (!reelId) {
    throw new Error("Reel ID is required.");
  }

  const snapshot = await get(
    ref(db, `${PATHS.reels}/${reelId}`)
  );

  if (!snapshot.exists()) {
    return null;
  }

  return {
    id: reelId,
    ...snapshot.val()
  };
}


/**
 * Get all Reels.
 * Admin use.
 */
export async function getAllReels() {
  const snapshot = await get(
    ref(db, PATHS.reels)
  );

  if (!snapshot.exists()) {
    return [];
  }

  const data = snapshot.val();

  return Object.entries(data).map(
    ([id, reel]) => ({
      id,
      ...reel
    })
  );
}


/**
 * Get active Reels.
 */
export async function getActiveReels() {
  const reelsQuery = query(
    ref(db, PATHS.reels),
    orderByChild("feedbackEnabled"),
    equalTo(true)
  );

  const snapshot =
    await get(reelsQuery);

  if (!snapshot.exists()) {
    return [];
  }

  const data = snapshot.val();

  return Object.entries(data)
    .map(([id, reel]) => ({
      id,
      ...reel
    }))
    .filter(
      (reel) =>
        reel.status === "active"
    );
}


/**
 * Create a Reel.
 *
 * Reel ID should be generated by the admin UI,
 * e.g. RB0001.
 */
export async function createReel(
  reel
) {
  if (!reel?.reelId) {
    throw new Error(
      "Reel ID is required."
    );
  }

  const reelRef = ref(
    db,
    `${PATHS.reels}/${reel.reelId}`
  );

  const existing =
    await get(reelRef);

  if (existing.exists()) {
    throw new Error(
      `Reel ${reel.reelId} already exists.`
    );
  }

  const reelData = {
    reelId:
      String(reel.reelId),

    title:
      reel.title?.trim() ||
      "Untitled Reel",

    reelUrl:
      reel.reelUrl?.trim() || "",

    thumbnailUrl:
      reel.thumbnailUrl?.trim() || "",

    status:
      reel.status || "active",

    feedbackEnabled:
      reel.feedbackEnabled !== false,

    createdAt:
      serverTimestamp(),

    updatedAt:
      serverTimestamp()
  };

  await set(
    reelRef,
    reelData
  );

  return {
    id: reel.reelId,
    ...reelData
  };
}


/**
 * Update Reel.
 */
export async function updateReel(
  reelId,
  changes
) {
  if (!reelId) {
    throw new Error(
      "Reel ID is required."
    );
  }

  const reelRef = ref(
    db,
    `${PATHS.reels}/${reelId}`
  );

  await update(
    reelRef,
    {
      ...changes,
      updatedAt:
        serverTimestamp()
    }
  );

  return getReel(reelId);
}


/**
 * Enable / disable a Reel.
 */
export async function setReelStatus(
  reelId,
  active
) {
  return updateReel(
    reelId,
    {
      status:
        active
          ? "active"
          : "inactive",

      feedbackEnabled:
        Boolean(active)
    }
  );
}


