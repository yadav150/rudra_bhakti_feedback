/**
 * Submit public feedback.
 *
 * A random Firebase push ID is generated.
 */
export async function submitFeedback(
  feedback
) {
  if (!feedback) {
    throw new Error(
      "Feedback data is required."
    );
  }

  if (!feedback.reelId) {
    throw new Error(
      "Reel ID is required."
    );
  }

  if (!feedback.sessionId) {
    throw new Error(
      "Session ID is required."
    );
  }

  if (
    !feedback.answers ||
    typeof feedback.answers !== "object"
  ) {
    throw new Error(
      "Answers are required."
    );
  }


  /*
   * Generate unique feedback ID.
   */
  const feedbackListRef =
    ref(db, PATHS.feedback);

  const newFeedbackRef =
    push(feedbackListRef);

  const feedbackId =
    newFeedbackRef.key;


  /*
   * Data saved to RTDB.
   */
  const feedbackData = {
    feedbackId,

    reelId:
      String(feedback.reelId),

    sessionId:
      String(feedback.sessionId),

    answers:
      feedback.answers || {},

    questionTiming:
      feedback.questionTiming || {},

    engagement:
      feedback.engagement || {},

    typing:
      feedback.typing || {},

    device:
      feedback.device || {},

    startedAt:
      feedback.startedAt || null,

    completedAt:
      feedback.completedAt || null,

    totalDurationMs:
      Number(
        feedback.totalDurationMs || 0
      ),

    createdAt:
      serverTimestamp()
  };


  await set(
    newFeedbackRef,
    feedbackData
  );


  return {
    id: feedbackId,
    ...feedbackData
  };
}


